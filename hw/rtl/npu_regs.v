// npu_regs: the NPU's control and status registers, on PCIe BAR0.
//
// AXI4-Lite slave, 32-bit data, one transaction at a time. The host reaches
// it through BAR0: the axi_pcie bridge's AXI master and an AXI4-Lite
// converter since phase 3 (XDMA's AXI-Lite master before). docs/register-map.md is the
// authoritative description; keep it in step with this file.
//
// Phase 1 registers prove the link: identity, a scratch register for
// read/write tests, a cycle counter for latency measurements, software LEDs,
// and a software-raised interrupt to exercise the MSI path. Phase 2 adds the
// DDR3 controller's status and counters of the DMA engine's AXI traffic, so
// the host can see memory-system problems without a JTAG cable, and the
// controls of mem_bw, the card-side DDR3 bandwidth engine. Phase 3 adds the
// command queue's configuration, doorbells and status (npu_cq,
// docs/command-queue.md).
//
// The handshake logic is AMD's AXI4-Lite slave template (Vivado 2025.2,
// Tools > Create and Package New IP > AXI4 peripheral, regenerated by
// hw/scripts/axil_template.tcl), with the template's slv_reg array replaced by
// the register map below. Two changes to its write side, both marked
// "Template change": the template accepts write data before the address and
// writes it to the previous address, and it can raise a second write response
// while the first is still waiting.

`timescale 1ns / 1ps
`default_nettype none

module npu_regs #(
  parameter [31:0] BUILD_ID      = 32'h0000_0000, // set by the build script
  parameter [15:0] CARD_MEM_MIB  = 16'd1024,      // card memory behind BAR1 DMA
  parameter [31:0] BW_CLK_KHZ    = 32'd100000     // mem_bw's clock (MIG ui_clk)
) (
  input  wire        clk,
  input  wire        rst_n,

  // AXI4-Lite slave
  input  wire [31:0] s_axil_awaddr,
  input  wire        s_axil_awvalid,
  output wire        s_axil_awready,
  input  wire [31:0] s_axil_wdata,
  input  wire [3:0]  s_axil_wstrb,
  input  wire        s_axil_wvalid,
  output wire        s_axil_wready,
  output wire [1:0]  s_axil_bresp,
  output wire        s_axil_bvalid,
  input  wire        s_axil_bready,
  input  wire [31:0] s_axil_araddr,
  input  wire        s_axil_arvalid,
  output wire        s_axil_arready,
  output reg  [31:0] s_axil_rdata,
  output wire [1:0]  s_axil_rresp,
  output wire        s_axil_rvalid,
  input  wire        s_axil_rready,

  // Status in, controls out
  input  wire        link_up,
  input  wire        ddr_calib_done,  // asynchronous (MIG clock domain)
  input  wire        ddr_mmcm_locked, // asynchronous (MIG clock domain)
  input  wire [31:0] dma_writes,      // AXI write bursts from the DMA engine
  input  wire [31:0] dma_reads,       // AXI read bursts from the DMA engine
  input  wire [31:0] dma_errors,      // non-OKAY AXI responses to the DMA engine

  // mem_bw: settings out (held while busy), results in
  output reg         bw_start,        // one-cycle pulse
  output wire        bw_read,
  output wire [4:0]  bw_outstanding,
  output wire [15:0] bw_seed,
  output reg  [31:0] bw_addr,
  output reg  [31:0] bw_len,
  input  wire        bw_busy,
  input  wire [31:0] bw_runs,
  input  wire [31:0] bw_cycles,
  input  wire [31:0] bw_mismatches,
  input  wire [31:0] bw_errors,
  output wire [1:0]  user_led,
  output wire        irq_req,
  input  wire        irq_ack,

  // Command queue (npu_cq)
  output wire [31:0] cycles_lo,       // timestamps for completions
  output reg         cq_enable,
  output reg         cq_irq_en,
  output reg  [3:0]  cq_log2,
  output reg  [63:0] cq_sq_base,
  output reg  [63:0] cq_cq_base,
  output reg         cq_sq_tail_wr,   // one-cycle doorbell pulses
  output reg         cq_cq_head_wr,
  output reg  [11:0] cq_doorbell,     // value for either doorbell
  input  wire        cq_busy,
  input  wire        cq_stalled,
  input  wire        cq_axi_err,
  input  wire        cq_cfg_err,
  input  wire [31:0] cq_completed
);

  // Register offsets (bytes)
  localparam [11:0] REG_ID       = 12'h000;
  localparam [11:0] REG_VERSION  = 12'h004;
  localparam [11:0] REG_BUILD    = 12'h008;
  localparam [11:0] REG_CAPS     = 12'h00C;
  localparam [11:0] REG_SCRATCH  = 12'h010;
  localparam [11:0] REG_CONTROL  = 12'h014;
  localparam [11:0] REG_STATUS   = 12'h018;
  localparam [11:0] REG_CYCLE_LO = 12'h020;
  localparam [11:0] REG_CYCLE_HI = 12'h024;
  localparam [11:0] REG_IRQ      = 12'h028;
  localparam [11:0] REG_DMA_WR   = 12'h030;
  localparam [11:0] REG_DMA_RD   = 12'h034;
  localparam [11:0] REG_DMA_ERR  = 12'h038;
  localparam [11:0] REG_BW_CTRL  = 12'h040;
  localparam [11:0] REG_BW_ADDR  = 12'h044;
  localparam [11:0] REG_BW_LEN   = 12'h048;
  localparam [11:0] REG_BW_RUNS  = 12'h04C;
  localparam [11:0] REG_BW_CYC   = 12'h050;
  localparam [11:0] REG_BW_MISM  = 12'h054;
  localparam [11:0] REG_BW_ERR   = 12'h058;
  localparam [11:0] REG_BW_CLK   = 12'h05C;
  localparam [11:0] REG_CQ_CTRL  = 12'h080;
  localparam [11:0] REG_CQ_LOG2  = 12'h084;
  localparam [11:0] REG_SQ_LO    = 12'h088;
  localparam [11:0] REG_SQ_HI    = 12'h08C;
  localparam [11:0] REG_CQB_LO   = 12'h090;
  localparam [11:0] REG_CQB_HI   = 12'h094;
  localparam [11:0] REG_SQ_TAIL  = 12'h098;
  localparam [11:0] REG_CQ_HEAD  = 12'h09C;
  localparam [11:0] REG_CQ_STAT  = 12'h0A0;
  localparam [11:0] REG_CQ_DONE  = 12'h0A4;

  localparam [31:0] ID_VALUE      = 32'h4E50_5530; // "NPU0"
  localparam [7:0]  VERSION_MAJOR = 8'd0;
  localparam [7:0]  VERSION_MINOR = 8'd4;
  localparam [7:0]  VERSION_PATCH = 8'd0;

  // CAPS: [31:16] card memory in MiB, [3] GEMM engine, [2] command queue,
  // [1] card memory is DDR3, [0] DMA path.
  localparam [31:0] CAPS_VALUE = {CARD_MEM_MIB, 12'd0, 1'b1, 1'b1, 1'b1, 1'b1};

  reg [31:0] scratch;
  reg [1:0]  control;
  reg        irq_level;   // REG_IRQ[0]: software-held interrupt request
  reg        irq_acked;   // REG_IRQ[1]: the MSI was granted (XDMA's ack before phase 3)
  reg [63:0] cycles;
  reg [31:0] cycle_hi_latch;
  reg [31:0] bw_ctrl;     // [1] read, [12:8] outstanding, [31:16] seed
  assign bw_read        = bw_ctrl[1];
  assign bw_outstanding = bw_ctrl[12:8];
  assign bw_seed        = bw_ctrl[31:16];

  assign user_led  = control;
  assign irq_req   = irq_level;
  assign cycles_lo = cycles[31:0];

  // DDR status crosses from the MIG clock; two flops per bit.
  (* ASYNC_REG = "TRUE" *) reg [1:0] ddr_sync1, ddr_sync2;
  always @(posedge clk) begin
    ddr_sync1 <= {ddr_mmcm_locked, ddr_calib_done};
    ddr_sync2 <= ddr_sync1;
  end

  always @(posedge clk) begin
    if (!rst_n) cycles <= 64'd0;
    else        cycles <= cycles + 64'd1;
  end

  // Template state encoding
  localparam [1:0] Idle = 2'b00, Raddr = 2'b10, Rdata = 2'b11, Waddr = 2'b10, Wdata = 2'b11;

  // ---------------------------------------------------------------------------
  // Write channel (template)
  reg        axi_awready;
  reg        axi_wready;
  reg        axi_bvalid;
  reg [11:0] axi_awaddr;
  reg [1:0]  state_write;

  // Template change: no new address or data while a response is waiting, and
  // in Waddr, data is accepted only together with its address.
  assign s_axil_awready = axi_awready && !axi_bvalid;
  assign s_axil_wready  = axi_wready && !axi_bvalid && (state_write == Wdata || s_axil_awvalid);
  assign s_axil_bvalid  = axi_bvalid;
  assign s_axil_bresp   = 2'b00; // OKAY, also for read-only and unmapped offsets

  always @(posedge clk) begin
    if (!rst_n) begin
      axi_awready <= 1'b0;
      axi_wready  <= 1'b0;
      axi_bvalid  <= 1'b0;
      axi_awaddr  <= 12'd0;
      state_write <= Idle;
    end else begin
      case (state_write)
        Idle: begin
          axi_awready <= 1'b1;
          axi_wready  <= 1'b1;
          state_write <= Waddr;
        end
        // Ready for an address, with or without its data; also retires the
        // previous response.
        Waddr: begin
          if (s_axil_awvalid && s_axil_awready) begin
            axi_awaddr <= s_axil_awaddr[11:0];
            if (s_axil_wvalid) begin
              axi_awready <= 1'b1;
              state_write <= Waddr;
              axi_bvalid  <= 1'b1;
            end else begin
              axi_awready <= 1'b0;
              state_write <= Wdata;
            end
          end else if (s_axil_bready && axi_bvalid) begin
            axi_bvalid <= 1'b0;
          end
        end
        // Address accepted, waiting for its data.
        Wdata: begin
          if (s_axil_wvalid) begin
            state_write <= Waddr;
            axi_bvalid  <= 1'b1;
            axi_awready <= 1'b1;
          end
        end
        default: state_write <= Idle;
      endcase
    end
  end

  // Register writes. Template change: only on a data handshake, at the
  // address that came with it (Waddr) or before it (Wdata).
  wire        wr_en   = s_axil_wvalid && s_axil_wready;
  wire [11:0] wr_addr = (state_write == Waddr) ? s_axil_awaddr[11:0] : axi_awaddr;

  function [31:0] apply_strb(input [31:0] old, input [31:0] new, input [3:0] strb);
    integer i;
    begin
      for (i = 0; i < 4; i = i + 1)
        apply_strb[i*8 +: 8] = strb[i] ? new[i*8 +: 8] : old[i*8 +: 8];
    end
  endfunction

  always @(posedge clk) begin
    if (!rst_n) begin
      scratch   <= 32'd0;
      control   <= 2'd0;
      irq_level <= 1'b0;
      irq_acked <= 1'b0;
      bw_ctrl   <= 32'd0;
      bw_addr   <= 32'd0;
      bw_len    <= 32'd0;
      bw_start  <= 1'b0;
      cq_enable <= 1'b0; cq_irq_en <= 1'b0; cq_log2 <= 4'd0;
      cq_sq_base <= 64'd0; cq_cq_base <= 64'd0;
      cq_sq_tail_wr <= 1'b0; cq_cq_head_wr <= 1'b0; cq_doorbell <= 12'd0;
    end else begin
      bw_start <= 1'b0;
      cq_sq_tail_wr <= 1'b0;
      cq_cq_head_wr <= 1'b0;
      if (irq_ack) irq_acked <= 1'b1;
      if (wr_en) begin
        case ({wr_addr[11:2], 2'b00})
          REG_SCRATCH: scratch <= apply_strb(scratch, s_axil_wdata, s_axil_wstrb);
          REG_CONTROL: if (s_axil_wstrb[0]) control <= s_axil_wdata[1:0];
          REG_IRQ: if (s_axil_wstrb[0]) begin
            irq_level <= s_axil_wdata[0];
            if (s_axil_wdata[1]) irq_acked <= 1'b0; // write 1 to clear
          end
          // mem_bw settings cross to the memory clock while a run is in
          // progress, so they ignore writes until it finishes.
          REG_BW_CTRL: if (!bw_busy) begin
            bw_ctrl  <= apply_strb(bw_ctrl, s_axil_wdata, s_axil_wstrb) & 32'hFFFF_1F02;
            bw_start <= s_axil_wstrb[0] && s_axil_wdata[0];
          end
          REG_BW_ADDR: if (!bw_busy) bw_addr <= apply_strb(bw_addr, s_axil_wdata, s_axil_wstrb);
          REG_BW_LEN:  if (!bw_busy) bw_len  <= apply_strb(bw_len,  s_axil_wdata, s_axil_wstrb);
          // Command queue. Ring settings ignore writes while it is enabled.
          REG_CQ_CTRL: if (s_axil_wstrb[0]) begin cq_enable <= s_axil_wdata[0]; cq_irq_en <= s_axil_wdata[1]; end
          REG_CQ_LOG2: if (!cq_enable && s_axil_wstrb[0]) cq_log2 <= s_axil_wdata[3:0];
          REG_SQ_LO:   if (!cq_enable) cq_sq_base[31:0]  <= apply_strb(cq_sq_base[31:0],  s_axil_wdata, s_axil_wstrb);
          REG_SQ_HI:   if (!cq_enable) cq_sq_base[63:32] <= apply_strb(cq_sq_base[63:32], s_axil_wdata, s_axil_wstrb);
          REG_CQB_LO:  if (!cq_enable) cq_cq_base[31:0]  <= apply_strb(cq_cq_base[31:0],  s_axil_wdata, s_axil_wstrb);
          REG_CQB_HI:  if (!cq_enable) cq_cq_base[63:32] <= apply_strb(cq_cq_base[63:32], s_axil_wdata, s_axil_wstrb);
          REG_SQ_TAIL: begin cq_doorbell <= s_axil_wdata[11:0]; cq_sq_tail_wr <= 1'b1; end
          REG_CQ_HEAD: begin cq_doorbell <= s_axil_wdata[11:0]; cq_cq_head_wr <= 1'b1; end
          default: ; // read-only or unmapped: ignored, still OKAY
        endcase
      end
    end
  end

  // ---------------------------------------------------------------------------
  // Read channel (template). RVALID rises in the cycle after the address
  // handshake, never in it: XDMA holds RREADY high between reads and drops a
  // response that arrives with the address (seen on hardware, 2026-11-04,
  // with an earlier version of this block).
  reg       axi_arready;
  reg       axi_rvalid;
  reg [1:0] state_read;

  assign s_axil_arready = axi_arready;
  assign s_axil_rvalid  = axi_rvalid;
  assign s_axil_rresp   = 2'b00;

  always @(posedge clk) begin
    if (!rst_n) begin
      axi_arready <= 1'b0;
      axi_rvalid  <= 1'b0;
      state_read  <= Idle;
    end else begin
      case (state_read)
        Idle: begin
          state_read  <= Raddr;
          axi_arready <= 1'b1;
        end
        Raddr: begin
          if (s_axil_arvalid && s_axil_arready) begin
            state_read  <= Rdata;
            axi_rvalid  <= 1'b1;
            axi_arready <= 1'b0;
          end
        end
        Rdata: begin
          if (s_axil_rvalid && s_axil_rready) begin
            axi_rvalid  <= 1'b0;
            axi_arready <= 1'b1;
            state_read  <= Raddr;
          end
        end
        default: state_read <= Idle;
      endcase
    end
  end

  // Read data, registered at the address handshake instead of the template's
  // combinational mux: reading CYCLE_LO latches CYCLE_HI there, so a LO-then-HI
  // pair is one coherent 64-bit sample.
  always @(posedge clk) begin
    if (!rst_n) begin
      s_axil_rdata   <= 32'd0;
      cycle_hi_latch <= 32'd0;
    end else if (s_axil_arvalid && s_axil_arready) begin
      case ({s_axil_araddr[11:2], 2'b00})
        REG_ID:       s_axil_rdata <= ID_VALUE;
        REG_VERSION:  s_axil_rdata <= {8'd0, VERSION_MAJOR, VERSION_MINOR, VERSION_PATCH};
        REG_BUILD:    s_axil_rdata <= BUILD_ID;
        REG_CAPS:     s_axil_rdata <= CAPS_VALUE;
        REG_SCRATCH:  s_axil_rdata <= scratch;
        REG_CONTROL:  s_axil_rdata <= {30'd0, control};
        REG_STATUS:   s_axil_rdata <= {29'd0, ddr_sync2, link_up};
        REG_CYCLE_LO: begin
          s_axil_rdata   <= cycles[31:0];
          cycle_hi_latch <= cycles[63:32];
        end
        REG_CYCLE_HI: s_axil_rdata <= cycle_hi_latch;
        REG_IRQ:      s_axil_rdata <= {30'd0, irq_acked, irq_level};
        REG_DMA_WR:   s_axil_rdata <= dma_writes;
        REG_DMA_RD:   s_axil_rdata <= dma_reads;
        REG_DMA_ERR:  s_axil_rdata <= dma_errors;
        REG_BW_CTRL:  s_axil_rdata <= {bw_ctrl[31:1], bw_busy};
        REG_BW_ADDR:  s_axil_rdata <= bw_addr;
        REG_BW_LEN:   s_axil_rdata <= bw_len;
        REG_BW_RUNS:  s_axil_rdata <= bw_runs;
        REG_BW_CYC:   s_axil_rdata <= bw_cycles;
        REG_BW_MISM:  s_axil_rdata <= bw_mismatches;
        REG_BW_ERR:   s_axil_rdata <= bw_errors;
        REG_BW_CLK:   s_axil_rdata <= BW_CLK_KHZ;
        REG_CQ_CTRL:  s_axil_rdata <= {30'd0, cq_irq_en, cq_enable};
        REG_CQ_LOG2:  s_axil_rdata <= {28'd0, cq_log2};
        REG_SQ_LO:    s_axil_rdata <= cq_sq_base[31:0];
        REG_SQ_HI:    s_axil_rdata <= cq_sq_base[63:32];
        REG_CQB_LO:   s_axil_rdata <= cq_cq_base[31:0];
        REG_CQB_HI:   s_axil_rdata <= cq_cq_base[63:32];
        REG_SQ_TAIL:  s_axil_rdata <= 32'd0;                 // doorbells are write-only
        REG_CQ_HEAD:  s_axil_rdata <= 32'd0;
        REG_CQ_STAT:  s_axil_rdata <= {28'd0, cq_cfg_err, cq_axi_err, cq_stalled, cq_busy};
        REG_CQ_DONE:  s_axil_rdata <= cq_completed;
        default:      s_axil_rdata <= 32'hDEAD_BEEF;
      endcase
    end
  end

endmodule

`default_nettype wire
